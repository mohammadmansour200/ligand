@Composable
fun LicensesRoot(onNavigateBack: () -> Unit) {
    Licenses(
        onNavigateBack = onNavigateBack
    )
}

@Composable
private fun Licenses(
    modifier: Modifier = Modifier,
    onNavigateBack: () -> Unit
) {
    val generated by produceLibraries {
        Res.readBytes("files/libraries.json").decodeToString()
    }

    val libraries = remember(generated) {
        generated?.libraries?.sortedBy { it.name.lowercase() }
    }

    Scaffold(
        modifier = modifier,
        topBar = {
            TopAppBar(
                title = { Text("Open Source Licenses") },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        IconWithTooltip(
                            icon = vectorResource(Res.drawable.arrow_back),
                            text = "Back",
                        )
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.surfaceContainer,
                ),
            )
        },
    ) { innerPadding ->
        if (libraries == null) {
            Box(
                modifier = Modifier.fillMaxSize().padding(innerPadding),
                contentAlignment = Alignment.Center,
            ) {
                CircularProgressIndicator()
            }
        } else {

            LazyColumn(
                modifier = Modifier.fillMaxSize(),
                contentPadding = innerPadding,
            ) {
                items(
                    items = libraries,
                    key = { it.uniqueId },
                ) { lib ->
                    LibraryItem(library = lib)
                }
            }
        }
    }
}

@Composable
private fun produceLibraries(
    block: suspend () -> String,
): State<Libs?> {
    return produceState(initialValue = null) {
        value = withContext(Dispatchers.Default) {
            Libs.Builder()
                .withJson(block())
                .build()
        }
    }
}
